#!/usr/bin/env bash
# =============================================================================
# 中佳 WMS 一键安装器 v1.0.1（由 deploy/v2/build/build-installer.sh 生成）
#
# 用法（先落盘校验，绝不 curl | bash）：
#   curl -fsSL <官方URL>/zjwms-installer.sh        -o /tmp/zjwms-installer.sh
#   curl -fsSL <官方URL>/zjwms-installer.sh.sha256 -o /tmp/zjwms-installer.sha256
#   (cd /tmp && sha256sum -c zjwms-installer.sha256)
#   sudo bash /tmp/zjwms-installer.sh [deploy 参数...]
#
#   bash zjwms-installer.sh --self-check   仅解压并校验载荷，不部署
#
# 本文件 = 引导器 + 内嵌 deploy/v2 工具链（SHA256 固定）。执行时解压工具链、
# 校验哈希后原样转入 zjwms deploy；GitHub Token 在部署过程中按提示输入。
# =============================================================================
ZJWMS_INSTALLER_VERSION="1.0.1"
ZJWMS_PAYLOAD_SHA256="c587bad6b4f9b6da4ec44353c32a43af976c78989a2c16089d9e05187259b6dc"

set -euo pipefail

die() { printf '[zjwms-installer] FATAL: %s\n' "$*" >&2; exit 1; }
log() { printf '[zjwms-installer] %s\n' "$*"; }

ZJWMS_TMP=""

cleanup() { [ -n "$ZJWMS_TMP" ] && rm -rf "$ZJWMS_TMP"; }
trap cleanup EXIT

extract_payload() {
  # $1 = 目标目录；从本文件尾部分离 base64 载荷，校验 SHA256 后解压
  local dest="$1" payload actual
  payload="$dest/bootstrap.tar.gz"
  sed -n '/^__ZJWMS_PAYLOAD__$/,/^__ZJWMS_END__$/p' "$0" | sed '1d;$d' \
    | base64 -d > "$payload" || die "载荷解码失败（安装器文件不完整？请重新下载）"
  actual="$(sha256sum "$payload" | awk '{print $1}')"
  [ "$actual" = "$ZJWMS_PAYLOAD_SHA256" ] \
    || die "载荷 SHA256 校验失败（期望 $ZJWMS_PAYLOAD_SHA256，实际 $actual）——安装器被改动或传输损坏，请重新下载"
  tar -xzf "$payload" -C "$dest" || die "载荷解压失败"
  [ -f "$dest/deploy/v2/zjwms" ] || die "载荷结构异常：deploy/v2/zjwms 缺失"
  [ -f "$dest/deploy/v2/conf/zjwms.env.example" ] || die "载荷结构异常：conf/zjwms.env.example 缺失"
}

case "${1:-}" in
  -h|--help|help)
    sed -n '3,14p' "$0" | sed 's/^# \{0,1\}//'
    exit 0 ;;
  --self-check)
    ZJWMS_TMP="$(mktemp -d /tmp/zjwms-installer.XXXXXX)"
    extract_payload "$ZJWMS_TMP"
    echo "SELF_CHECK=OK version=$ZJWMS_INSTALLER_VERSION payload_sha256=$ZJWMS_PAYLOAD_SHA256"
    exit 0 ;;
esac

[ -f "$0" ] || die "本安装器需以文件方式运行（先 curl -o 保存，再 sudo bash），不支持管道执行"

if [ "$(id -u)" != "0" ]; then
  die "请用 root 运行：sudo bash $0"
fi

ZJWMS_TMP="$(mktemp -d /tmp/zjwms-install.XXXXXX)"
extract_payload "$ZJWMS_TMP"
log "工具链就绪（v$ZJWMS_INSTALLER_VERSION，payload SHA256 $ZJWMS_PAYLOAD_SHA256）"
log "转入 zjwms deploy（参数原样透传）……"
set +e
bash "$ZJWMS_TMP/deploy/v2/zjwms" deploy "$@"
rc=$?
set -e
exit "$rc"


#!/usr/bin/env bash
# =============================================================================
# 中佳 WMS 一键安装器 v1.0.6（由 deploy/v2/build/build-installer.sh 生成）
#
# 用法（先落盘校验，绝不 curl | bash；不传 --version = 安装最新正式版）：
#   curl -fsSL <官方URL>/zjwms-installer.sh        -o /tmp/zjwms-installer.sh
#   curl -fsSL <官方URL>/zjwms-installer.sh.sha256 -o /tmp/zjwms-installer.sha256
#   (cd /tmp && sha256sum -c zjwms-installer.sha256)
#   sudo bash /tmp/zjwms-installer.sh                        # Latest 默认
#   sudo bash /tmp/zjwms-installer.sh --proxy http://主机:端口 # 经代理部署
#   sudo bash /tmp/zjwms-installer.sh --version 1.0.6    # 显式版本（可选）
#       （首参恰为字面 deploy 时自动摘除一次，绝不透传 deploy deploy）
#
#   bash zjwms-installer.sh --self-check   仅解压并校验载荷，不部署
#
#   sudo bash /tmp/zjwms-installer.sh --toolchain-only      # 仅升级部署工具链
#       （V1.0.6：已部署服务器的 zjwms 工具链在线升级；不下载/切换应用
#        Release、不写数据库、不恢复基线、不重置管理员、不重启后端、不改
#        current——应用更新永远走 sudo zjwms update）
#
# 本文件 = 引导器 + 内嵌 deploy/v2 工具链（SHA256 固定）。执行时解压工具链、
# 校验哈希后转入 zjwms deploy；GitHub Token 在部署过程中按提示输入。
# 网络与凭据预检全部通过前零系统副作用（V1.0.4）。
# =============================================================================
ZJWMS_INSTALLER_VERSION="1.0.6"
ZJWMS_PAYLOAD_SHA256="565df3c9aa43354cdd057db7c45a568b673add49e244e0aae9d05a585111c71e"

set -euo pipefail

die() { printf '[zjwms-installer] FATAL: %s\n' "$*" >&2; exit 1; }
log() { printf '[zjwms-installer] %s\n' "$*"; }

ZJWMS_TMP=""

# 注意必须用 if 形式：`[ -n "$ZJWMS_TMP" ] && rm -rf …` 在 -h 提前退出
# （ZJWMS_TMP 为空）时以状态 1 结束，EXIT trap 会把整个安装器的退出码
# 覆盖成 1（v1.0.1 的 -h 即由此返回 1，v1.0.1-1 修复）
cleanup() { if [ -n "$ZJWMS_TMP" ]; then rm -rf "$ZJWMS_TMP"; fi; }
trap cleanup EXIT

extract_payload() {
  # $1 = 目标目录；从本文件尾部分离 base64 载荷，校验 SHA256 后解压
  local dest="$1" payload actual
  payload="$dest/bootstrap.tar.gz"
  sed -n '/^__ZJWMS_PAYLOAD__$/,/^__ZJWMS_END__$/p' "$0" | sed '1d;$d' \
    | base64 -d > "$payload" || die "载荷解码失败（安装器文件不完整？请重新下载）"
  actual="$(sha256sum "$payload" | awk '{print $1}')"
  [ "$actual" = "$ZJWMS_PAYLOAD_SHA256" ] \
    || die "载荷 SHA256 校验失败（期望 $ZJWMS_PAYLOAD_SHA256，实际 $actual）——安装器被改动或传输损坏，请重新下载"
  tar -xzf "$payload" -C "$dest" || die "载荷解压失败"
  [ -f "$dest/deploy/v2/zjwms" ] || die "载荷结构异常：deploy/v2/zjwms 缺失"
  [ -f "$dest/deploy/v2/conf/zjwms.env.example" ] || die "载荷结构异常：conf/zjwms.env.example 缺失"
}

case "${1:-}" in
  -h|--help|help)
    sed -n '3,23p' "$0" | sed 's/^# \{0,1\}//'
    exit 0 ;;
  --self-check)
    ZJWMS_TMP="$(mktemp -d /tmp/zjwms-installer.XXXXXX)"
    extract_payload "$ZJWMS_TMP"
    echo "SELF_CHECK=OK version=$ZJWMS_INSTALLER_VERSION payload_sha256=$ZJWMS_PAYLOAD_SHA256"
    exit 0 ;;
esac

[ -f "$0" ] || die "本安装器需以文件方式运行（先 curl -o 保存，再 sudo bash），不支持管道执行"

if [ "$(id -u)" != "0" ]; then
  die "请用 root 运行：sudo bash $0"
fi

ZJWMS_TMP="$(mktemp -d /tmp/zjwms-install.XXXXXX)"
extract_payload "$ZJWMS_TMP"
log "工具链就绪（v$ZJWMS_INSTALLER_VERSION，payload SHA256 $ZJWMS_PAYLOAD_SHA256）"

# --toolchain-only（V1.0.6 §6）：已部署服务器的工具链在线升级——转发到
# zjwms toolchain-update，载荷即刚解压校验过的工具链；其余参数（--proxy 等）
# 原样透传。职责边界由 toolchain-update 侧硬约束：不下载/切换应用 Release、
# 不写数据库、不恢复基线、不重置管理员、不重启后端、不改 current
if [ "${1:-}" = "--toolchain-only" ]; then
  shift
  log "转入 zjwms toolchain-update（仅更新部署工具链，不动应用/数据库/服务）……"
  set +e
  bash "$ZJWMS_TMP/deploy/v2/zjwms" toolchain-update --from "$ZJWMS_TMP/deploy/v2" "$@"
  rc=$?
  set -e
  exit "$rc"
fi

# CLI 契约（单层语义，2026-10-07 公网 E2E 实证修复）：安装器本身就是 deploy
# 安装器，参数即 deploy 参数，子命令由下方调用补齐；兼容已发布 v1.0.1 文档
# 写法「installer.sh deploy --version …」——首参恰为字面 deploy 时摘除一次。
# 双 deploy 透传曾触发 zjwms「deploy 未知参数：deploy」即死，绝不重演。
if [ "${1:-}" = "deploy" ]; then
  shift
fi
log "转入 zjwms deploy……"
set +e
bash "$ZJWMS_TMP/deploy/v2/zjwms" deploy "$@"
rc=$?
set -e
exit "$rc"

